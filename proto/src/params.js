export function clockText(t, p = PARAMS) {
  const whole = Math.floor(t + p.epsilon) % p.secondsPerDay;
  return [Math.floor(whole / p.secondsPerHour), Math.floor(whole / p.secondsPerMinute) % p.secondsPerMinute,
    whole % p.secondsPerMinute].map(n => String(n).padStart(2, '0')).join(':');
}
